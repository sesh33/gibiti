"use client";
import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { Download, FileSpreadsheet, FileText, ShieldCheck } from "lucide-react";
import Link from "next/link";
import { PageHeading } from "@/components/page-heading";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/api-client";
import type { ReportKind } from "@/domains/eldorado/seller-contracts";
const reports = [
  {
    id: "sold-orders",
    title: "Sales and seller fees",
    detail:
      "Official CSV with gross amounts, seller fees, net income and category. Values come from Eldorado's report.",
    icon: FileSpreadsheet,
  },
  {
    id: "orders",
    title: "Detailed orders",
    detail:
      "Official CSV with products, quantities, states, prices and available review/cancellation details.",
    icon: FileSpreadsheet,
  },
  {
    id: "invoice",
    title: "Seller invoice",
    detail:
      "Official invoice generated by Eldorado for the selected UTC date range. The verified response is PDF.",
    icon: FileText,
  },
] as const;
export function ReportsCenter({ configured }: { configured: boolean }) {
  const me = useQuery({
    queryKey: ["me"],
    queryFn: () => api<{ permissions: string[] }>("/api/me"),
    enabled: configured,
  });
  const [kind, setKind] = useState<ReportKind>("sold-orders"),
    [from, setFrom] = useState(
      () => new Date().toISOString().slice(0, 7) + "-01",
    ),
    [until, setUntil] = useState(() => new Date().toISOString().slice(0, 10)),
    [busy, setBusy] = useState(false),
    [message, setMessage] = useState("");
  const allowed =
    !!me.data?.permissions.includes("reports.export") &&
    !!me.data?.permissions.includes("orders.read");
  async function download(event: React.FormEvent) {
    event.preventDefault();
    if (busy) return;
    setBusy(true);
    setMessage("");
    try {
      const response = await fetch("/api/reports/download", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ kind, from, until }),
        cache: "no-store",
      });
      if (!response.ok) {
        const error = await response.json().catch(() => null);
        throw new Error(
          error?.error?.message ??
            "The report could not be downloaded. Try again later.",
        );
      }
      const type = response.headers.get("content-type") ?? "";
      if (!type.startsWith("text/csv") && !type.startsWith("application/pdf"))
        throw new Error("An unsupported file format was returned.");
      const blob = await response.blob(),
        url = URL.createObjectURL(blob),
        anchor = document.createElement("a");
      anchor.href = url;
      anchor.download = `eldorado-${kind}-${from}-${until}.${type.startsWith("application/pdf") ? "pdf" : "csv"}`;
      anchor.click();
      setTimeout(() => URL.revokeObjectURL(url), 5000);
      setMessage(
        "Official report downloaded. The export was audited. No listing or order was modified.",
      );
    } catch (error) {
      setMessage(
        error instanceof Error ? error.message : "The download failed.",
      );
    } finally {
      setBusy(false);
    }
  }
  return (
    <>
      <PageHeading
        eyebrow="OFFICIAL SELLER REPORTING"
        title="Your operation, with the numbers."
        description="Download the account-wide reports supplied by Eldorado. Individual staff access, MFA and an audited export protect financial data."
      />
      <div className="report-card-grid">
        {reports.map((report) => (
          <button
            type="button"
            aria-pressed={kind === report.id}
            className={`report-option ${kind === report.id ? "selected" : ""}`}
            onClick={() => setKind(report.id)}
            key={report.id}
            disabled={busy}
          >
            <report.icon size={24} />
            <strong>{report.title}</strong>
            <span>{report.detail}</span>
            <small>
              {report.id === "invoice" ? "PDF invoice" : "Spreadsheet-safe CSV"}
            </small>
          </button>
        ))}
      </div>
      <section className="data-panel settings-section">
        <h2>Choose your reporting period</h2>
        <p className="scope-note">
          Dates are inclusive in UTC. This application allows up to 367 calendar
          days and a 10 MiB download; shorten the period if needed. This is an
          Eldorado account report, independent of the locally synchronized page
          count.
        </p>
        <form className="catalog-editor-form" onSubmit={download}>
          <div className="reply-fields">
            <label className="field-label">
              From date
              <input
                aria-label="Report from date"
                type="date"
                required
                value={from}
                onChange={(e) => setFrom(e.target.value)}
                disabled={busy}
              />
            </label>
            <label className="field-label">
              Through date
              <input
                aria-label="Report through date"
                type="date"
                required
                min={from}
                value={until}
                onChange={(e) => setUntil(e.target.value)}
                disabled={busy}
              />
            </label>
          </div>
          <div className="reply-toolbar">
            <Button disabled={!allowed || busy}>
              <Download size={16} />
              {busy ? "Preparing official report…" : "Download official report"}
            </Button>
            <Link href="/mfa">Verify your authenticator</Link>
          </div>
        </form>
        {!allowed && (
          <p className="scope-note">
            Account-wide report export and full order-read permission are
            required.
          </p>
        )}
        <p className="scope-note">
          <ShieldCheck size={14} style={{ display: "inline" }} /> CSV text cells
          are escaped against spreadsheet formulas. The report file is not
          stored in browser query caches.
        </p>
        {message && (
          <p role="status" className="inline-feedback">
            {message}
          </p>
        )}
      </section>
    </>
  );
}
